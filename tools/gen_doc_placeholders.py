"""
gen_doc_placeholders.py -- write placeholder blocks into unwritten doc pages

Run from the repo root:
    python3 tools/gen_doc_placeholders.py [--check]

    --check   report what would change, write nothing

Reads tools/doc_status.yaml. For each listed page under docs/, keeps the
SPDX header and the "# Title" line unchanged and writes a generated block
between <!-- placeholder:start --> and <!-- placeholder:end -->. A rerun
replaces only that block.

A page is touched only if its body, below the title, is empty apart from an
existing placeholder block. A page with written content is skipped and
listed. Exit status is 1 if the table has errors, 0 otherwise.
"""

import json
import re
import sys
from pathlib import Path

import yaml

# -- Configuration -------------------------------------------------------------

TABLE_FILE    = Path("tools/doc_status.yaml")
DOCS_DIR      = Path("docs")
SESSIONS_FILE = Path("docs/sessions.json")
DEMO_DOCS_DIR = Path("examples/fe_demo/docs")

BLOG_URL = "https://uarchlabs.github.io/blog/{}/"
TASK_URL = "https://uarchlabs.github.io/pacino/sessions/#{}"
DEMO_URL = ("https://github.com/uarchlabs/pacino/blob/main/"
            "examples/fe_demo/docs/{}.md")

START = "<!-- placeholder:start -->"
END   = "<!-- placeholder:end -->"

RTL_WORDS = {
    "done":          "RTL complete",
    "active":        "RTL in progress",
    "planned":       "RTL planned",
    "not-in-design": "Not in the current design",
}
DOCS_WORDS = {
    "planned": "Documentation planned",
    "active":  "Documentation in progress",
}
ENTRY_KEYS = {"rtl", "docs", "covers", "see", "guess"}

BLOCK_RE = re.compile(re.escape(START) + r".*?" + re.escape(END), re.S)

# -- Table validation ----------------------------------------------------------

def load_task_ids():
    data = json.loads(SESSIONS_FILE.read_text())
    return {s["id"] for s in data.get("sessions", [])}


def check_entry(key, e, task_ids, errors):
    where = f"{TABLE_FILE}: {key}"
    if not isinstance(e, dict):
        errors.append(f"{where}: entry is not a mapping")
        return
    for k in sorted(set(e) - ENTRY_KEYS):
        errors.append(f"{where}: unknown field '{k}'")
    if e.get("rtl") not in RTL_WORDS:
        errors.append(f"{where}: rtl must be one of {', '.join(RTL_WORDS)}")
    if e.get("docs") not in DOCS_WORDS:
        errors.append(f"{where}: docs must be one of {', '.join(DOCS_WORDS)}")
    if not str(e.get("covers") or "").strip():
        errors.append(f"{where}: covers is empty")
    for item in e.get("see") or []:
        if not isinstance(item, dict):
            errors.append(f"{where}: see item is not a mapping: {item!r}")
        elif "blog" in item:
            if not item.get("title"):
                errors.append(f"{where}: blog {item['blog']} has no title")
        elif "tasks" in item:
            for tid in item["tasks"]:
                if tid not in task_ids:
                    errors.append(f"{where}: IA task {tid} is not in "
                                  f"{SESSIONS_FILE}")
        elif "demo" in item:
            if not (DEMO_DOCS_DIR / f"{item['demo']}.md").is_file():
                errors.append(f"{where}: demo {item['demo']} not found in "
                              f"{DEMO_DOCS_DIR}")
        else:
            errors.append(f"{where}: see item needs blog, tasks or demo")

# -- Rendering -----------------------------------------------------------------

def demo_title(name):
    # First heading of the scenario doc, e.g. "# fd06_loop_pred: Loop ..."
    for line in (DEMO_DOCS_DIR / f"{name}.md").read_text().splitlines():
        if line.startswith("# "):
            return line[2:].strip()
    return name


def see_line(item):
    if "blog" in item:
        return f"Blog: [{item['title']}]({BLOG_URL.format(item['blog'])})"
    if "tasks" in item:
        links = ", ".join(f"[{t}]({TASK_URL.format(t)})"
                          for t in item["tasks"])
        word = "IA task" if len(item["tasks"]) == 1 else "IA tasks"
        return f"{word}: {links}"
    return (f"Frontend demo: [{demo_title(item['demo'])}]"
            f"({DEMO_URL.format(item['demo'])})")


def render_block(e):
    covers = str(e["covers"]).strip()
    if not covers.endswith("."):
        covers += "."
    lines = [
        START,
        "<!-- Generated by tools/gen_doc_placeholders.py from "
        "tools/doc_status.yaml.",
        "     Edit the table and rerun; edits made here are overwritten. -->",
        "",
        '!!! note "Not written yet"',
        "",
        f"    **Status:** {RTL_WORDS[e['rtl']]}. "
        f"{DOCS_WORDS[e['docs']]}.",
        "",
        f"    This page will cover {covers}",
    ]
    see = e.get("see") or []
    if see:
        lines += ["", "    Meanwhile:", ""]
        lines += [f"    - {see_line(item)}" for item in see]
    lines += ["", END]
    return "\n".join(lines)

# -- Page handling -------------------------------------------------------------

def split_page(text):
    """Return (head, body): head is the comment header and the title line.

    Returns None if the page does not open with comment lines and blank
    lines followed by a "# Title" line.
    """
    lines = text.splitlines(keepends=True)
    in_comment = False
    for i, line in enumerate(lines):
        s = line.strip()
        if in_comment:
            in_comment = "-->" not in s
            continue
        if not s:
            continue
        if s.startswith("<!--"):
            in_comment = "-->" not in s
            continue
        if s.startswith("# "):
            return "".join(lines[:i + 1]), "".join(lines[i + 1:])
        return None
    return None


def is_empty_body(body):
    return not BLOCK_RE.sub("", body).strip()

# -- Main ----------------------------------------------------------------------

def main():
    check_only = "--check" in sys.argv[1:]
    table = yaml.safe_load(TABLE_FILE.read_text()) or {}
    task_ids = load_task_ids()

    errors = []
    for key, e in table.items():
        check_entry(key, e, task_ids, errors)
        if not (DOCS_DIR / key).is_file():
            errors.append(f"{TABLE_FILE}: {key}: no such page in {DOCS_DIR}")
    if errors:
        for msg in errors:
            print(f"error: {msg}", file=sys.stderr)
        return 1

    changed, unchanged, skipped = [], [], []
    for key, e in table.items():
        path = DOCS_DIR / key
        text = path.read_text()
        parts = split_page(text)
        if parts is None or not is_empty_body(parts[1]):
            skipped.append(key)
            continue
        new = parts[0].rstrip("\n") + "\n\n" + render_block(e) + "\n"
        if new == text:
            unchanged.append(key)
            continue
        changed.append(key)
        if not check_only:
            path.write_text(new)

    # Unwritten pages the table does not list.
    unlisted = []
    for path in sorted(DOCS_DIR.rglob("*.md")):
        key = path.relative_to(DOCS_DIR).as_posix()
        parts = split_page(path.read_text())
        if key not in table and parts and is_empty_body(parts[1]):
            unlisted.append(key)

    verb = "would change" if check_only else "changed"
    print(f"{len(changed)} {verb}, {len(unchanged)} unchanged, "
          f"{len(skipped)} skipped")
    for key in skipped:
        print(f"skipped, page has written content: {key}")
    for key in unlisted:
        print(f"not in {TABLE_FILE}, left empty: {key}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
